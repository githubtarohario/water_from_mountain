//=============================================================================
// Terrain.h
//   蛇行した谷を持つ「山の地形」を生成・描画するクラス。
//
//   地形は高さマップ (2 次元配列 y = h(x, z)) として表現する。
//   高さは HeightFunction で手続き的に計算する:
//     ・谷の中心線 ValleyCenterX(z) を sin の和で蛇行させる
//     ・谷の中心からの距離が大きいほど高く (両側に山)
//     ・上流 (-z) から下流 (+z) に向かって全体を傾ける (水が流れるように)
//     ・fBm ノイズと尾根状ノイズで岩肌の凹凸を加える
//
//   このクラスは描画だけでなく、SPH の粒子衝突用に
//   任意座標の高さ (GetHeight) と法線 (GetNormal) も提供する。
//=============================================================================
#pragma once

#include "Graphics.h"
#include <DirectXMath.h>
#include <vector>

class Terrain
{
public:
    // 地形の設定値
    static constexpr int   GRID_N     = 257;     // 1 辺あたりの頂点数 (セル数 = GRID_N - 1)
    static constexpr float WORLD_SIZE = 60.0f;   // 地形の 1 辺の長さ (x, z ともに -30～+30)
    static constexpr float HALF_SIZE  = WORLD_SIZE * 0.5f;

    //-------------------------------------------------------------------------
    // 関数名 : Initialize
    // 概要   : 高さマップ生成 → メッシュ作成 → 岩テクスチャ生成 → シェーダー作成
    // 引数   : gfx : Graphics (デバイス取得用)
    // 戻り値 : true = 成功, false = 失敗
    //-------------------------------------------------------------------------
    bool Initialize(Graphics& gfx);

    //-------------------------------------------------------------------------
    // 関数名 : Render
    // 概要   : 地形メッシュを描画する (定数バッファ b0 は呼び出し側で設定済みとする)
    // 引数   : gfx : Graphics (コンテキスト取得用)
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Render(Graphics& gfx);

    //-------------------------------------------------------------------------
    // 関数名 : GetHeight
    // 概要   : 任意のワールド座標 (x, z) における地面の高さを双線形補間で返す
    // 引数   : x, z : ワールド座標 (範囲外は端の値にクランプ)
    // 戻り値 : 地面の高さ y
    //-------------------------------------------------------------------------
    float GetHeight(float x, float z) const;

    //-------------------------------------------------------------------------
    // 関数名 : GetNormal
    // 概要   : 任意のワールド座標 (x, z) における地面の法線 (単位ベクトル) を返す
    //          中心差分で ∂h/∂x, ∂h/∂z を求め n = normalize(-hx, 1, -hz) とする
    // 引数   : x, z : ワールド座標
    // 戻り値 : 上向きの単位法線ベクトル
    //-------------------------------------------------------------------------
    DirectX::XMFLOAT3 GetNormal(float x, float z) const;

    //-------------------------------------------------------------------------
    // 関数名 : ValleyCenterX
    // 概要   : 谷の中心線の x 座標を z の関数として返す (蛇行カーブ)
    // 引数   : z : ワールド座標の z
    // 戻り値 : 谷の中心の x 座標
    //-------------------------------------------------------------------------
    static float ValleyCenterX(float z);

private:
    // 頂点フォーマット (HLSL の入力レイアウトと一致させる)
    struct Vertex
    {
        DirectX::XMFLOAT3 pos;     // ワールド座標 (地形はワールド行列 = 単位行列)
        DirectX::XMFLOAT3 normal;  // 法線
        DirectX::XMFLOAT2 uv;      // テクスチャ座標
    };

    //-------------------------------------------------------------------------
    // 関数名 : HeightFunction
    // 概要   : 地形の高さを手続き的に計算する (高さマップの元になる関数)
    // 引数   : x, z : ワールド座標
    // 戻り値 : 高さ y
    //-------------------------------------------------------------------------
    static float HeightFunction(float x, float z);

    //-------------------------------------------------------------------------
    // 関数名 : BuildHeightMap
    // 概要   : GRID_N × GRID_N の格子点すべてで HeightFunction を評価し m_heights に保存
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void BuildHeightMap();

    //-------------------------------------------------------------------------
    // 関数名 : BuildMesh
    // 概要   : 高さマップから頂点バッファ・インデックスバッファを作成する
    // 引数   : gfx : Graphics
    // 戻り値 : true = 成功, false = 失敗
    //-------------------------------------------------------------------------
    bool BuildMesh(Graphics& gfx);

    //-------------------------------------------------------------------------
    // 関数名 : CreateRockTexture
    // 概要   : 岩肌テクスチャを用意する。
    //          assets フォルダの画像ファイル (ROCK_TEXTURE_FILES の順に探す) を
    //          読み込み、見つからない/読めない場合はノイズによる手続き生成に切り替える。
    // 引数   : gfx : Graphics
    // 戻り値 : true = 成功, false = 失敗 (どちらの方法でも作れなかった)
    //-------------------------------------------------------------------------
    bool CreateRockTexture(Graphics& gfx);

    //-------------------------------------------------------------------------
    // 関数名 : CreateProceduralRockTexture
    // 概要   : ノイズから岩肌風のテクスチャを CPU で生成し、GPU テクスチャにする
    //          (画像ファイルがないときのフォールバック)
    // 引数   : gfx : Graphics
    // 戻り値 : true = 成功, false = 失敗
    //-------------------------------------------------------------------------
    bool CreateProceduralRockTexture(Graphics& gfx);

    //-------------------------------------------------------------------------
    // 関数名 : CreateShaders
    // 概要   : Terrain.hlsl をコンパイルし、頂点/ピクセルシェーダーと入力レイアウトを作る
    // 引数   : gfx : Graphics
    // 戻り値 : true = 成功, false = 失敗
    //-------------------------------------------------------------------------
    bool CreateShaders(Graphics& gfx);

    std::vector<float> m_heights;                 // 高さマップ (GRID_N * GRID_N 個、[z * GRID_N + x])
    float m_cellSize = WORLD_SIZE / (GRID_N - 1); // 格子 1 セルの長さ

    ComPtr<ID3D11Buffer>              m_vertexBuffer;  // 頂点バッファ
    ComPtr<ID3D11Buffer>              m_indexBuffer;   // インデックスバッファ (32bit)
    UINT                              m_indexCount = 0;// インデックス数
    ComPtr<ID3D11VertexShader>        m_vs;            // 頂点シェーダー
    ComPtr<ID3D11PixelShader>         m_ps;            // ピクセルシェーダー
    ComPtr<ID3D11InputLayout>         m_inputLayout;   // 頂点入力レイアウト
    ComPtr<ID3D11ShaderResourceView>  m_rockTexSRV;    // 岩テクスチャのビュー
    bool                              m_textureFromFile = false;   // true = 画像ファイル由来, false = 手続き生成

public:
    // 岩テクスチャとして探す画像ファイル名 (assets フォルダ内、先頭から順に試す)
    static constexpr const wchar_t* ROCK_TEXTURE_FILES[] = { L"rock.png", L"rock.jpg", L"rock.jpeg", L"rock.bmp" };

    //-------------------------------------------------------------------------
    // 関数名 : IsTextureFromFile
    // 概要   : 岩テクスチャが画像ファイルから読み込まれたかを返す (タイトル表示用)
    // 引数   : なし
    // 戻り値 : true = ファイル由来, false = 手続き生成
    //-------------------------------------------------------------------------
    bool IsTextureFromFile() const { return m_textureFromFile; }
};
