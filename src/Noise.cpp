    //-------------------------------------------------------------------------
    // Perlin2D
    //   アルゴリズム:
    //     1. 評価点を囲む 4 つの格子点 (X,Y),(X+1,Y),(X,Y+1),(X+1,Y+1) を求める
    //     2. 各格子点のハッシュ値から勾配を決め、評価点との内積を取る
    //     3. 4 つの内積を Fade 曲線で双線形補間する
    //-------------------------------------------------------------------------
    float Perlin2D(float x, float y)
    {
        // 評価点を含む格子セルの左下の整数座標。& 255 で 0～255 に折り返し、
        // 置換テーブル (256 要素) の範囲に収める
        const int X = static_cast<int>(std::floor(x)) & 255;
        const int Y = static_cast<int>(std::floor(y)) & 255;

        // セル内での相対位置 (0～1)。左下が (0,0)、右上が (1,1)
        const float xf = x - std::floor(x);
        const float yf = y - std::floor(y);

        // 補間係数 (Fade 曲線で緩和)。そのまま xf を使うと格子の境目に折れ目が出る
        const float u = Fade(xf);
        const float v = Fade(yf);

        // 4 隅のハッシュ値。テーブルを 2 回引くことで x と y が混ざり、
        // 規則性のない値になる (aa = 左下, ab = 左上, ba = 右下, bb = 右上)
        const int aa = s_perm[s_perm[X] + Y];
        const int ab = s_perm[s_perm[X] + Y + 1];
        const int ba = s_perm[s_perm[X + 1] + Y];
        const int bb = s_perm[s_perm[X + 1] + Y + 1];

        // x 方向に補間してから y 方向に補間 (双線形補間)
        const float x1 = Lerp(Grad(aa, xf, yf), Grad(ba, xf - 1.0f, yf), u);
        const float x2 = Lerp(Grad(ab, xf, yf - 1.0f), Grad(bb, xf - 1.0f, yf - 1.0f), u);
        return Lerp(x1, x2, v);
    }

    //-------------------------------------------------------------------------
    // Fbm2D
    //   アルゴリズム:
    //     sum = Σ amplitude_i * Perlin2D(x * frequency_i, y * frequency_i)
    //     frequency_i = lacunarity^i,  amplitude_i = gain^i
    //     最後に振幅の合計で割って -1～1 に正規化する
    //-------------------------------------------------------------------------
    float Fbm2D(float x, float y, int octaves, float lacunarity, float gain)
    {
        float sum = 0.0f;        // ノイズの累積値
        float amplitude = 1.0f;  // 現在のオクターブの振幅 (層が進むごとに小さくなる)
        float frequency = 1.0f;  // 現在のオクターブの周波数 (層が進むごとに細かくなる)
        float norm = 0.0f;       // 正規化用: 振幅の合計

        for (int i = 0; i < octaves; ++i)
        {
            // 座標に frequency を掛けると模様が細かくなり、値に amplitude を掛けると起伏が小さくなる
            sum += amplitude * Perlin2D(x * frequency, y * frequency);
            norm += amplitude;
            amplitude *= gain;         // 既定 0.5 = 次の層は振幅が半分
            frequency *= lacunarity;   // 既定 2.0 = 次の層は 2 倍細かい
        }
        return sum / norm;       // 振幅の合計で割り、層数によらず -1～1 に収める
    }

    //-------------------------------------------------------------------------
    // Ridged2D
    //   アルゴリズム:
    //     各オクターブで  r = 1 - |Perlin2D|  を計算する。
    //     ノイズが 0 を横切る場所で r が 1 になり、鋭い「尾根」が現れる。
    //     r^2 にすることで尾根をさらに細く鋭くしている。
    //-------------------------------------------------------------------------
    float Ridged2D(float x, float y, int octaves)
    {
        float sum = 0.0f;
        float amplitude = 1.0f;
        float frequency = 1.0f;
        float norm = 0.0f;

        for (int i = 0; i < octaves; ++i)
        {
            // 絶対値を取って 1 から引くと、ノイズが 0 を横切る線の上で r = 1 になり、
            // そこが尾根 (稜線や岩の割れ目) として浮かび上がる
            float r = 1.0f - std::fabs(Perlin2D(x * frequency, y * frequency));
            r = r * r;   // 2 乗すると尾根の幅が細くなり、より鋭くなる
            sum += amplitude * r;
            norm += amplitude;
            amplitude *= 0.5f;
            frequency *= 2.0f;
        }
        return sum / norm;
    }

    //-------------------------------------------------------------------------
    // Perlin2DPeriodic
    //   Perlin2D と同じだが、格子の整数座標を period で割った余りにする。
    //   これにより X+1 が period に達したとき 0 に戻り、端と端がつながる。
    //-------------------------------------------------------------------------
    float Perlin2DPeriodic(float x, float y, int period)
    {
        const int Xi = static_cast<int>(std::floor(x));   // 格子セルの左下の整数座標
        const int Yi = static_cast<int>(std::floor(y));

        // 座標を period で折り返すことで、period 離れた格子点が同じ勾配を持つようになり、
        // テクスチャの右端と左端 (上端と下端) が滑らかにつながる。
        // C++ の % は負の値に対して負を返すので、((v % p) + p) % p で正に直す
        auto wrap = [period](int v) { return ((v % period) + period) % period; };
        const int X0 = wrap(Xi) & 255;
        const int Y0 = wrap(Yi) & 255;
        const int X1 = wrap(Xi + 1) & 255;
        const int Y1 = wrap(Yi + 1) & 255;

        const float xf = x - std::floor(x);
        const float yf = y - std::floor(y);
        const float u = Fade(xf);
        const float v = Fade(yf);

        const int aa = s_perm[s_perm[X0] + Y0];
        const int ab = s_perm[s_perm[X0] + Y1];
        const int ba = s_perm[s_perm[X1] + Y0];
        const int bb = s_perm[s_perm[X1] + Y1];

        const float x1 = Lerp(Grad(aa, xf, yf), Grad(ba, xf - 1.0f, yf), u);
        const float x2 = Lerp(Grad(ab, xf, yf - 1.0f), Grad(bb, xf - 1.0f, yf - 1.0f), u);
        return Lerp(x1, x2, v);
    }

    //-------------------------------------------------------------------------
    // FbmTileable
    //-------------------------------------------------------------------------
    float FbmTileable(float u, float v, int basePeriod, int octaves)
    {
        float sum = 0.0f;
        float amplitude = 1.0f;
        float norm = 0.0f;
        int period = basePeriod;   // このオクターブの周期 (格子数)

        for (int i = 0; i < octaves; ++i)
        {
            sum += amplitude * Perlin2DPeriodic(u * period, v * period, period);
            norm += amplitude;
            amplitude *= 0.5f;
            period *= 2;
        }
        return sum / norm;
    }

    //-------------------------------------------------------------------------
    // RidgedTileable
    //-------------------------------------------------------------------------
    float RidgedTileable(float u, float v, int basePeriod, int octaves)
    {
        float sum = 0.0f;
        float amplitude = 1.0f;
        float norm = 0.0f;
        int period = basePeriod;

        for (int i = 0; i < octaves; ++i)
        {
            float r = 1.0f - std::fabs(Perlin2DPeriodic(u * period, v * period, period));
            r = r * r;
            sum += amplitude * r;
            norm += amplitude;
            amplitude *= 0.5f;
            period *= 2;
        }
        return sum / norm;
    }
