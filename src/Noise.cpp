    //-------------------------------------------------------------------------
    // 関数名 : Fade
    // 概要   : 補間用の緩和曲線 6t^5 - 15t^4 + 10t^3
    //          単純な線形補間だと格子の境界で折れ目が見えるため、
    //          1 階・2 階微分が両端で 0 になるこの曲線で滑らかにする。
    // 引数   : t : 0～1 の補間パラメータ
    // 戻り値 : 0～1 に緩和された値
    //-------------------------------------------------------------------------
    inline float Fade(float t)
    {
        return t * t * t * (t * (t * 6.0f - 15.0f) + 10.0f);
    }

    //-------------------------------------------------------------------------
    // 関数名 : Lerp
    // 概要   : 線形補間  a + (b - a) * t
    // 引数   : a, b : 補間の両端の値
    //          t    : 0 なら a、1 なら b
    // 戻り値 : 補間結果
    //-------------------------------------------------------------------------
    inline float Lerp(float a, float b, float t)
    {
        return a + (b - a) * t;
    }

    //-------------------------------------------------------------------------
    // 関数名 : Grad
    // 概要   : ハッシュ値から 8 方向のうち 1 つの勾配ベクトルを選び、
    //          格子点から評価点へのベクトル (x, y) との内積を返す
    // 引数   : hash : 置換テーブルから得たハッシュ値
    //          x, y : 格子点から評価点への相対ベクトル
    // 戻り値 : 勾配ベクトルと (x, y) の内積
    //-------------------------------------------------------------------------
    inline float Grad(int hash, float x, float y)
    {
        // 下位 3 ビットで 8 方向を選ぶ
        switch (hash & 7)
        {
        case 0: return  x + y;
        case 1: return -x + y;
        case 2: return  x - y;
        case 3: return -x - y;
        case 4: return  x;
        case 5: return -x;
        case 6: return  y;
        default: return -y;
        }
    }
