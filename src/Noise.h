//=============================================================================
// Noise.h
//   地形の起伏や岩肌テクスチャを作るための「パーリンノイズ」を提供するモジュール。
//
//   パーリンノイズとは:
//     格子点ごとにランダムな勾配ベクトルを割り当て、
//     位置と各格子点の勾配の内積を滑らかに補間することで
//     「連続していてランダムに見える値」を作るアルゴリズム。
//     自然物(山・雲・岩)の表現によく使われる。
//
//   fBm (fractional Brownian motion) とは:
//     周波数を倍々に、振幅を半分ずつにしたノイズを何層も足し合わせる手法。
//     大きなうねりと細かい凹凸を同時に表現できる。
//=============================================================================
#pragma once

namespace Noise
{
    //-------------------------------------------------------------------------
    // 関数名 : Perlin2D
    // 概要   : 2 次元パーリンノイズを 1 点だけ評価する
    // 引数   : x, y : 評価する座標 (任意の実数。1.0 刻みで格子点をまたぐ)
    // 戻り値 : おおよそ -1.0 ～ +1.0 の範囲の値
    //-------------------------------------------------------------------------
    float Perlin2D(float x, float y);

    //-------------------------------------------------------------------------
    // 関数名 : Fbm2D
    // 概要   : Perlin2D を複数オクターブ重ね合わせた fBm ノイズ
    // 引数   : x, y        : 評価する座標
    //          octaves     : 重ねる層の数 (多いほど細部が増えるが計算コスト増)
    //          lacunarity  : 1 層進むごとに周波数を何倍にするか (通常 2.0)
    //          gain        : 1 層進むごとに振幅を何倍にするか (通常 0.5)
    // 戻り値 : おおよそ -1.0 ～ +1.0 に正規化された値
    //-------------------------------------------------------------------------
    float Fbm2D(float x, float y, int octaves = 6, float lacunarity = 2.0f, float gain = 0.5f);

    //-------------------------------------------------------------------------
    // 関数名 : Ridged2D
    // 概要   : 「1 - |noise|」を重ね合わせた尾根状ノイズ。
    //          岩の亀裂や山の稜線のような鋭い筋を作るのに向いている。
    // 引数   : x, y     : 評価する座標
    //          octaves  : 重ねる層の数
    // 戻り値 : 0.0 ～ 1.0 程度 (値が大きいほど稜線/亀裂に近い)
    //-------------------------------------------------------------------------
    float Ridged2D(float x, float y, int octaves = 4);

    //-------------------------------------------------------------------------
    // 関数名 : Perlin2DPeriodic
    // 概要   : 格子座標を period で折り返す「周期的」パーリンノイズ。
    //          x, y が period の整数倍ずれても同じ値になるため、
    //          継ぎ目なく繰り返せる (タイリング可能な) テクスチャに使える。
    // 引数   : x, y   : 評価する座標
    //          period : 繰り返し周期 (格子単位、正の整数)
    // 戻り値 : おおよそ -1.0 ～ +1.0
    //-------------------------------------------------------------------------
    float Perlin2DPeriodic(float x, float y, int period);

    //-------------------------------------------------------------------------
    // 関数名 : FbmTileable
    // 概要   : タイリング可能な fBm。u, v ∈ [0,1) を入力とし、
    //          各オクターブで period を倍にしながら Perlin2DPeriodic を重ねる。
    // 引数   : u, v       : テクスチャ座標 (0～1)
    //          basePeriod : 最初のオクターブの周期 (テクスチャ 1 枚あたりの格子数)
    //          octaves    : 重ねる層の数
    // 戻り値 : おおよそ -1.0 ～ +1.0
    //-------------------------------------------------------------------------
    float FbmTileable(float u, float v, int basePeriod, int octaves = 6);

    //-------------------------------------------------------------------------
    // 関数名 : RidgedTileable
    // 概要   : タイリング可能な尾根状ノイズ (岩の亀裂表現用)
    // 引数   : u, v       : テクスチャ座標 (0～1)
    //          basePeriod : 最初のオクターブの周期
    //          octaves    : 重ねる層の数
    // 戻り値 : 0.0 ～ 1.0 程度
    //-------------------------------------------------------------------------
    float RidgedTileable(float u, float v, int basePeriod, int octaves = 4);
}
