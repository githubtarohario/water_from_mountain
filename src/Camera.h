//=============================================================================
// Camera.h
//   注視点の周りを回る「オービットカメラ」。
//
//   パラメータ:
//     m_target   : 注視点 (カメラが常に見る点)
//     m_yaw      : 水平方向の回転角 [rad]  (y 軸周り)
//     m_pitch    : 上下方向の見下ろし角 [rad]
//     m_distance : 注視点からカメラまでの距離
//
//   カメラ位置は極座標から求める:
//     pos = target + distance * ( cos(pitch)*sin(yaw), sin(pitch), cos(pitch)*cos(yaw) )
//=============================================================================
#pragma once

#include <DirectXMath.h>

class Camera
{
public:
    Camera();

    //-------------------------------------------------------------------------
    // 関数名 : Rotate
    // 概要   : マウスドラッグ量に応じて yaw / pitch を回転させる
    // 引数   : dYaw   : 水平回転の増分 [rad]
    //          dPitch : 上下回転の増分 [rad]
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Rotate(float dYaw, float dPitch);

    //-------------------------------------------------------------------------
    // 関数名 : Zoom
    // 概要   : 注視点との距離を倍率で変える (マウスホイール用)
    // 引数   : factor : 距離に掛ける倍率 (1 より小さいと近づく)
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Zoom(float factor);

    //-------------------------------------------------------------------------
    // 関数名 : Pan
    // 概要   : 注視点をカメラの右方向・上方向に平行移動する (右ドラッグ用)
    // 引数   : dx : 右方向の移動量 (ワールド単位)
    //          dy : 上方向の移動量 (ワールド単位)
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Pan(float dx, float dy);

    //-------------------------------------------------------------------------
    // 関数名 : GetPosition
    // 概要   : 現在のカメラのワールド座標を返す
    // 引数   : なし
    // 戻り値 : カメラ位置
    //-------------------------------------------------------------------------
    DirectX::XMFLOAT3 GetPosition() const;

    //-------------------------------------------------------------------------
    // 関数名 : GetViewMatrix
    // 概要   : 左手系のビュー行列 (XMMatrixLookAtLH) を返す
    // 引数   : なし
    // 戻り値 : ビュー行列 (転置前・行優先)
    //-------------------------------------------------------------------------
    DirectX::XMMATRIX GetViewMatrix() const;

    //-------------------------------------------------------------------------
    // 関数名 : GetProjMatrix
    // 概要   : 透視投影行列 (XMMatrixPerspectiveFovLH) を返す
    // 引数   : aspect : 画面の縦横比 (幅 / 高さ)
    // 戻り値 : 射影行列 (転置前・行優先)
    //-------------------------------------------------------------------------
    DirectX::XMMATRIX GetProjMatrix(float aspect) const;

    float GetNearZ() const { return m_nearZ; }
    float GetFarZ()  const { return m_farZ; }

private:
    DirectX::XMFLOAT3 m_target;   // 注視点
    float m_yaw;                  // 水平回転角 [rad]
    float m_pitch;                // 見下ろし角 [rad] (正で上から見下ろす)
    float m_distance;             // 注視点までの距離
    float m_fovY;                 // 垂直画角 [rad]
    float m_nearZ;                // ニアクリップ距離
    float m_farZ;                 // ファークリップ距離
};
