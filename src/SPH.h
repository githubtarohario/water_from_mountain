//=============================================================================
// SPH.h
//   SPH (Smoothed Particle Hydrodynamics, 平滑化粒子流体力学) による流体シミュレーション。
//
//   SPH の考え方:
//     流体を多数の「粒子」で表し、各粒子の物理量 (密度・圧力など) を
//     近傍粒子の値を「カーネル関数 W」で重み付けして足し合わせることで求める。
//       密度   ρ_i = Σ_j m W_poly6(|x_i - x_j|, h)
//       圧力   p_i = k (ρ_i - ρ0)                 … 状態方程式 (ρ0 は静止密度)
//       圧力力 f_i^p = -Σ_j m (p_i + p_j)/(2ρ_j) ∇W_spiky
//       粘性力 f_i^v =  μ Σ_j m (v_j - v_i)/ρ_j  ∇²W_visc
//       加速度 a_i = (f_i^p + f_i^v)/ρ_i + g
//     h は「平滑化半径」で、この距離より遠い粒子は無視する。
//     (Müller et al., "Particle-Based Fluid Simulation for Interactive Applications", 2003)
//
//   近傍探索:
//     毎ステップ全粒子対を調べると O(N^2) になるので、
//     空間を一辺 h の格子に切り、粒子をセルに振り分けてから
//     周囲 27 セルだけを調べる (空間ハッシュ + カウンティングソート)。
//
//   境界:
//     地形 (Terrain) の高さマップと衝突判定し、粒子が地面より下に行かないようにする。
//     下流の端 (z = +HALF_SIZE) に達した粒子は消去し、上流のエミッタから再投入する。
//
//   並列化:
//     粒子ごとに独立な計算 (密度・力・積分) は OpenMP で並列化している。
//=============================================================================
#pragma once

#include "Terrain.h"
#include <DirectXMath.h>
#include <vector>
#include <cstdint>

//-----------------------------------------------------------------------------
// SPHParams : シミュレーションの調整パラメータ
//-----------------------------------------------------------------------------
struct SPHParams
{
    // ---- 粒子の物理量 ----
    float particleSpacing = 0.30f;   // 粒子の初期間隔 [m] (粒子径とみなす)
    float smoothingRadius = 0.60f;   // 平滑化半径 h [m] (通常は間隔の 2 倍)
    float restDensity     = 1000.0f; // 静止密度 ρ0 [kg/m^3] (水)
    float stiffness       = 2000.0f; // 圧力の硬さ k (大きいほど非圧縮に近づくが不安定になる)
    float viscosity       = 0.40f;   // 粘性係数 μ (数値安定化のため実際の水より大きめ。流れをまとまらせる)
    float gravity         = 9.8f;    // 重力加速度 [m/s^2]
    float maxSpeed        = 10.0f;   // 速度の上限 [m/s] (発散防止の安全弁)
    float maxAcceleration = 250.0f;  // 加速度の上限 [m/s^2] (壁際の圧力スパイクによる「蹴り」を抑える)

    // ---- 時間刻み ----
    float timeStep        = 0.003f;  // 1 サブステップの時間 [s] (CFL 条件 dt < 0.4 h / c を満たすこと)
    int   maxSubsteps     = 5;       // 1 フレームで実行するサブステップ数の上限
                                     // (処理落ち時はサブステップを増やさず、実時間より遅く進める)

    // ---- 境界との衝突 ----
    float restitution     = 0.0f;    // 反発係数 (0 = 跳ね返らない)
    float friction        = 0.010f;  // 接地時に 1 サブステップあたり速度に掛ける減衰率 (地面との摩擦)
    float contactZone     = 0.30f;   // 地面からこの高さ [m] 以内を「接触ゾーン」とし、
                                     // 地面に近いほど強く減衰させて跳ね上がりを抑える
    float contactDamping  = 0.06f;   // 接触ゾーンの最下部で 1 サブステップあたりに掛ける減衰率
    float airDrag         = 0.015f;  // 孤立粒子 (飛沫) に 1 サブステップあたり掛ける空気抵抗
    int   sparseNeighbors = 8;       // 近傍がこの数未満なら孤立粒子とみなす (自分自身を含む)

    // ---- エミッタ (粒子の投入口) ----
    int   maxParticles    = 12000;   // 最大粒子数
    int   maxNeighbors    = 96;      // 1 粒子あたり記録する近傍粒子数の上限
    int   emitWidth       = 14;      // 1 回の投入で横に並べる粒子数
    int   emitHeight      = 4;       // 1 回の投入で縦に積む粒子数
    float emitSpeed       = 4.0f;    // 投入時の初速 [m/s] (下流 +z 方向)
    float emitZ           = -Terrain::HALF_SIZE + 2.5f;  // 投入位置の z (上流の端付近)
    float emitLift        = 0.8f;    // 地面から投入位置までの高さ [m]
};

class SPH
{
public:
    //-------------------------------------------------------------------------
    // 関数名 : Initialize
    // 概要   : パラメータを設定し、配列を最大粒子数分だけ確保する
    // 引数   : terrain : 衝突判定に使う地形 (寿命は SPH より長いこと)
    //          params  : シミュレーションパラメータ
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Initialize(const Terrain* terrain, const SPHParams& params);

    //-------------------------------------------------------------------------
    // 関数名 : Reset
    // 概要   : 全粒子を消去し、経過時間とエミッタを初期状態に戻す
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Reset();

    //-------------------------------------------------------------------------
    // 関数名 : Update
    // 概要   : 実時間 frameTime 秒ぶんシミュレーションを進める。
    //          内部では timeStep 刻みのサブステップに分割して Step を繰り返す。
    // 引数   : frameTime : 前フレームからの経過時間 [s]
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Update(float frameTime);

    //-------------------------------------------------------------------------
    // 関数名 : GetRenderData
    // 概要   : 描画用に (x, y, z, 速さ) を詰めた配列を返す。
    //          速さは近傍粒子との平均を取って平滑化する (SPH 特有の細かな速度の
    //          ばらつきで色がまだらにならないようにするため)。
    // 引数   : なし
    // 戻り値 : 有効粒子数ぶんの XMFLOAT4 配列 (w = 平滑化した速さ [m/s])
    //-------------------------------------------------------------------------
    const std::vector<DirectX::XMFLOAT4>& GetRenderData();

    int   GetParticleCount() const { return m_count; }
    float GetSimTime()       const { return m_time; }
    const SPHParams& GetParams() const { return m_params; }

private:
    //-------------------------------------------------------------------------
    // 関数名 : Step
    // 概要   : 1 サブステップぶん進める
    //          手順: エミッタ → 近傍格子構築 → 密度/圧力 → 力 → 積分+衝突 → 排水
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Step();

    //-------------------------------------------------------------------------
    // 関数名 : Emit
    // 概要   : 投入タイマーを進め、必要な回数だけ EmitSheet を呼ぶ
    // 引数   : dt : このサブステップの時間 [s]
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Emit(float dt);

    //-------------------------------------------------------------------------
    // 関数名 : EmitSheet
    // 概要   : 上流の谷底に emitWidth × emitHeight の粒子の板を 1 枚置く
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void EmitSheet();

    //-------------------------------------------------------------------------
    // 関数名 : BuildGrid
    // 概要   : 全粒子をセルに振り分ける (カウンティングソート)。
    //          結果: m_cellStart[key] ～ m_cellStart[key+1] の範囲の m_sorted[] が
    //                ハッシュ key のセルに属する粒子番号。
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void BuildGrid();

    //-------------------------------------------------------------------------
    // 関数名 : BuildNeighborLists
    // 概要   : 各粒子について距離 < h の近傍粒子番号を m_neighbors に記録する (並列)。
    //          密度計算と力計算の両方で同じ近傍を使うため、探索を 1 回で済ませる。
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void BuildNeighborLists();

    //-------------------------------------------------------------------------
    // 関数名 : ComputeDensityPressure
    // 概要   : 各粒子の密度 ρ と圧力 p を計算する (並列)
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void ComputeDensityPressure();

    //-------------------------------------------------------------------------
    // 関数名 : ComputeForces
    // 概要   : 圧力力・粘性力・重力から各粒子の加速度を計算する (並列)
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void ComputeForces();

    //-------------------------------------------------------------------------
    // 関数名 : Integrate
    // 概要   : シンプレクティック・オイラー法で速度と位置を更新し、境界と衝突させる (並列)
    //            v ← v + a dt,  x ← x + v dt
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void Integrate();

    //-------------------------------------------------------------------------
    // 関数名 : ResolveCollision
    // 概要   : 粒子 i を地形と側壁に対して衝突処理する
    //          地面より下なら地面の上に押し戻し、法線方向の速度成分を除去する
    // 引数   : i : 粒子番号
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void ResolveCollision(int i);

    //-------------------------------------------------------------------------
    // 関数名 : RemoveDrained
    // 概要   : 下流の端に達した粒子を配列から取り除く (末尾と入れ替えて詰める)
    // 引数   : なし
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void RemoveDrained();

    //-------------------------------------------------------------------------
    // 関数名 : CellCoord
    // 概要   : 位置から格子セルの整数座標を求める (floor(p / h))
    // 引数   : p : 位置
    // 戻り値 : セル座標 (負もあり得る)
    //-------------------------------------------------------------------------
    DirectX::XMINT3 CellCoord(const DirectX::XMFLOAT3& p) const;

    //-------------------------------------------------------------------------
    // 関数名 : HashCell
    // 概要   : セル座標をハッシュ表の添え字 (0 ～ tableSize-1) に写像する
    //          3 つの大きな素数との積の XOR を取る (Teschner et al., 2003)
    // 引数   : cx, cy, cz : セル座標
    // 戻り値 : ハッシュ表の添え字
    //-------------------------------------------------------------------------
    uint32_t HashCell(int cx, int cy, int cz) const;

    //-------------------------------------------------------------------------
    // 関数名 : ForEachNeighbor
    // 概要   : 粒子 i の周囲 27 セルを走査し、距離 < h の粒子 j ごとに
    //          func(j, dx, dy, dz, r2) を呼ぶ (dx.. は x_i - x_j, r2 はその 2 乗長)
    //          ハッシュの衝突で別セルの粒子が混ざらないよう、セル座標の一致も確認する
    // 引数   : i    : 注目粒子の番号
    //          func : 近傍ごとに呼ばれる関数オブジェクト
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    template <class F>
    void ForEachNeighbor(int i, F&& func) const;

    const Terrain* m_terrain = nullptr;   // 衝突判定用の地形
    SPHParams      m_params;              // パラメータ

    // ---- 粒子データ (添え字 = 粒子番号、有効なのは 0 ～ m_count-1) ----
    std::vector<DirectX::XMFLOAT3> m_pos;      // 位置 [m]
    std::vector<DirectX::XMFLOAT3> m_vel;      // 速度 [m/s]
    std::vector<DirectX::XMFLOAT3> m_acc;      // 加速度 [m/s^2]
    std::vector<float>             m_density;  // 密度 ρ [kg/m^3]
    std::vector<float>             m_pressure; // 圧力 p
    int   m_count = 0;                         // 現在の有効粒子数

    // ---- 近傍探索用の格子 ----
    uint32_t                     m_tableSize = 0;   // ハッシュ表の大きさ (2 のべき乗)
    uint32_t                     m_tableMask = 0;   // tableSize - 1 (剰余の代わりにビットマスクで使う)
    std::vector<DirectX::XMINT3> m_cell;            // 各粒子のセル座標
    std::vector<uint32_t>        m_cellKey;         // 各粒子のハッシュ値
    std::vector<uint32_t>        m_cellStart;       // ハッシュ値ごとの開始位置 (tableSize + 1 個)
    std::vector<uint32_t>        m_cellFill;        // 振り分け作業用のカウンタ
    std::vector<int>             m_sorted;          // ハッシュ値順に並べた粒子番号
    std::vector<int>             m_neighbors;       // 近傍粒子番号 [i * maxNeighbors + k]
    std::vector<int>             m_neighborCount;   // 各粒子の近傍数

    // ---- カーネル関数の係数 (h から事前計算) ----
    float m_h  = 0.0f;        // 平滑化半径 h
    float m_h2 = 0.0f;        // h^2
    float m_mass = 0.0f;      // 粒子 1 個の質量 m = ρ0 * spacing^3
    float m_poly6Coef = 0.0f; // 315 / (64 π h^9)
    float m_spikyGradCoef = 0.0f; // 45 / (π h^6)  (勾配の大きさ用)
    float m_viscLapCoef = 0.0f;   // 45 / (π h^6)  (ラプラシアン用)

    // ---- エミッタ・時間 ----
    float m_time = 0.0f;       // シミュレーション経過時間 [s]
    float m_emitTimer = 0.0f;  // 前回投入からの経過時間 [s]
    uint32_t m_rng = 12345u;   // 投入位置のジッタ用の乱数状態 (xorshift)

    // ---- 描画用 ----
    std::vector<float>             m_speed;        // 各粒子の速さ |v| (平滑化前の作業用)
    std::vector<DirectX::XMFLOAT4> m_renderData;   // (x, y, z, 平滑化した速さ)
};
