//=============================================================================
// MeshLoader.h
//   Wavefront OBJ 形式のメッシュファイルを読み込むモジュール。
//   Blender などの DCC ツールから書き出した地形メッシュを取り込むために使う。
//
//   対応している OBJ の要素:
//     v  x y z        頂点座標
//     vt u v          テクスチャ座標
//     vn x y z        法線
//     f  a/b/c ...    面 (頂点/UV/法線 の組。"a", "a/b", "a//c", "a/b/c" の全形式と
//                     負の相対インデックスに対応。4 頂点以上の多角形は扇状に三角形分割)
//   無視する要素: o, g, s, usemtl, mtllib, # (コメント) など
//
//   OBJ は「同じ座標でも UV や法線が違えば別頂点」として扱う必要があるため、
//   (v, vt, vn) の組ごとに頂点を作り、同じ組は再利用してインデックスを共有する。
//=============================================================================
#pragma once

#include <DirectXMath.h>
#include <string>
#include <vector>
#include <cstdint>

namespace MeshLoader
{
    //-------------------------------------------------------------------------
    // 構造体 : MeshVertex
    // 概要   : 読み込んだメッシュの 1 頂点 (Terrain::Vertex と同じ並び)
    //-------------------------------------------------------------------------
    struct MeshVertex
    {
        DirectX::XMFLOAT3 pos;     // 位置
        DirectX::XMFLOAT3 normal;  // 法線 (ファイルに無ければ ComputeSmoothNormals で計算)
        DirectX::XMFLOAT2 uv;      // テクスチャ座標 (ファイルに無ければ 0)
    };

    //-------------------------------------------------------------------------
    // 構造体 : MeshData
    // 概要   : 読み込み結果。三角形リスト (indices は 3 個で 1 三角形)
    //-------------------------------------------------------------------------
    struct MeshData
    {
        std::vector<MeshVertex> vertices;   // 頂点配列
        std::vector<uint32_t>   indices;    // 三角形インデックス
        DirectX::XMFLOAT3 boundsMin = { 0, 0, 0 };   // バウンディングボックス最小
        DirectX::XMFLOAT3 boundsMax = { 0, 0, 0 };   // バウンディングボックス最大
        bool hasNormals = false;            // ファイルに vn があったか
        bool hasUVs     = false;            // ファイルに vt があったか
    };

    //-------------------------------------------------------------------------
    // 関数名 : LoadObj
    // 概要   : OBJ ファイルを読み込み、三角形リストのメッシュにする
    // 引数   : path     : OBJ ファイルのパス
    //          out      : [出力] メッシュデータ
    //          errorMsg : [出力・省略可] 失敗時の理由
    // 戻り値 : true = 成功 (三角形が 1 つ以上ある), false = 失敗
    //-------------------------------------------------------------------------
    bool LoadObj(const std::wstring& path, MeshData& out, std::string* errorMsg = nullptr);

    //-------------------------------------------------------------------------
    // 関数名 : ComputeSmoothNormals
    // 概要   : 各三角形の面法線を頂点に加算して正規化し、滑らかな頂点法線を作る
    //          (面積の大きい三角形ほど強く寄与する重み付き平均になる)
    // 引数   : mesh : 対象メッシュ (normal が上書きされる)
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void ComputeSmoothNormals(MeshData& mesh);

    //-------------------------------------------------------------------------
    // 関数名 : ComputeBounds
    // 概要   : 全頂点からバウンディングボックス (boundsMin / boundsMax) を計算する
    // 引数   : mesh : 対象メッシュ
    // 戻り値 : なし
    //-------------------------------------------------------------------------
    void ComputeBounds(MeshData& mesh);
}
